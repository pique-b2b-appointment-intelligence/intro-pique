// Validatie: geen em-dashes, geen zin die begint met Geen/Niet
let warnings = 0;
for (const r of rows) {
  const body = letter(r);
  if (body.includes('—')) { console.log(`  ! em-dash in ${r.company}`); warnings++; }
  for (const sentence of body.replace(/\n/g, ' ').split(/(?<=[.!?:])\s+/)) {
    if (/^(Geen|Niet)\b/.test(sentence.trim())) { console.log(`  ! zin start met Geen/Niet in ${r.company}: ${sentence.trim().slice(0,40)}`); warnings++; }
  }
}
console.log(warnings === 0 ? 'Validatie: schoon.' : `Validatie: ${warnings} waarschuwing(en).`);
